#!/usr/bin/env node
// Claude imports the shared rulebook instead of maintaining a second copy.
// --check validates the adapter and preserved context without comparing rule text.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const root = process.cwd();
const SOURCE = "AGENTS.md";
const TARGET = "CLAUDE.md";
const HEADER = "<!-- ADG Claude adapter v1. Edit shared instructions in AGENTS.md. -->\n\n@AGENTS.md\n";
const NATIVE_ADAPTER = "# Project instructions\n\n@AGENTS.md\n";
const NOTES = "\nPreserved Claude context (consult when relevant):\n\n";
const OLD_BANNER = [
  "<!--",
  "  GENERATED FROM AGENTS.md — DO NOT EDIT THIS FILE.",
  "  CLAUDE.md is a generated mirror so Claude Code and Codex read one rulebook.",
  "  Edit AGENTS.md, then run: npm run claude:generate",
  "-->", "", "",
].join("\n");
const digest = bytes => createHash("sha256").update(bytes).digest("hex");

// Reject every symlink component, including dangling links. All paths are fixed
// or parsed against the content-addressed archive grammar, never user paths.
function safePath(rel) {
  let current = root;
  for (const part of rel.split("/")) {
    if (!part || part === "." || part === "..") throw new Error(`Unsafe path: ${rel}`);
    current = path.join(current, part);
    try {
      if (fs.lstatSync(current).isSymbolicLink()) throw new Error(`Refusing symlink: ${rel}`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  return current;
}

function render(refs = []) {
  return HEADER + (refs.length ? NOTES + refs.map(ref => `- [Original Claude notes](${ref})\n`).join("") : "");
}

function adapterRefs(text) {
  if (text === HEADER || text === NATIVE_ADAPTER || text === "@AGENTS.md\n") return [];
  if (!text.startsWith(HEADER + NOTES)) return null;
  const lines = text.slice((HEADER + NOTES).length).split("\n");
  if (lines.pop() !== "" || !lines.length) return null;
  const refs = [];
  for (const line of lines) {
    const match = /^- \[Original Claude notes\]\((docs\/adg-preserved\/CLAUDE-[a-f0-9]{64}\.md)\)$/.exec(line);
    if (!match) return null;
    refs.push(match[1]);
  }
  return refs;
}

function preservedLinks(text) {
  return [...text.matchAll(/^- \[Original Claude notes\]\((docs\/adg-preserved\/CLAUDE-[a-f0-9]{64}\.md)\)$/gm)].map(match => match[1]);
}

function validateRefs(refs) {
  const queue = [...refs], seen = new Set();
  for (let i = 0; i < queue.length; i++) {
    const ref = queue[i];
    if (seen.has(ref)) continue;
    seen.add(ref);
    const content = fs.readFileSync(safePath(ref));
    if (!ref.endsWith(`CLAUDE-${digest(content)}.md`)) throw new Error(`Preserved context changed: ${ref}`);
    queue.push(...preservedLinks(content.toString("utf8")));
  }
}

function preserve(bytes) {
  const ref = `docs/adg-preserved/CLAUDE-${digest(bytes)}.md`;
  const dest = safePath(ref);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  try {
    fs.writeFileSync(dest, bytes, { flag: "wx" });
  } catch (error) {
    if (error.code !== "EEXIST") throw error;
    if (!fs.readFileSync(dest).equals(bytes)) throw new Error(`Preservation collision: ${ref}`);
  }
  return ref;
}

try {
  const source = fs.readFileSync(safePath(SOURCE), "utf8");
  const target = safePath(TARGET);
  const bytes = fs.existsSync(target) ? fs.readFileSync(target) : null;
  const current = bytes?.toString("utf8") ?? "";
  const refs = adapterRefs(current);
  if (process.argv.includes("--check")) {
    if (refs === null) throw new Error(`${TARGET} is missing or is not the thin ADG adapter. Run: npm run claude:generate`);
    validateRefs(refs);
    console.log(`${TARGET} imports ${SOURCE}; preserved context is intact.`);
  } else {
    // Exact legacy mirrors contain no unique notes. A stale or customized mirror
    // is retained whole: its banner alone never proves it is safe to discard.
    const priorRefs = preservedLinks(current);
    validateRefs(priorRefs);
    const nextRefs = refs ?? (bytes?.length && current !== OLD_BANNER + source
      ? [...new Set([...priorRefs, preserve(bytes)])] : []);
    validateRefs(nextRefs);
    const generated = render(nextRefs);
    fs.writeFileSync(target, generated, "utf8");
    console.log(`Wrote ${TARGET} importing ${SOURCE} (${Buffer.byteLength(generated)} bytes).`);
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
