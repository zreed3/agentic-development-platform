#!/usr/bin/env node
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const generator = path.resolve("scripts/adg-claude-md.mjs");
const fixtures = [];
const hash = text => createHash("sha256").update(text).digest("hex");
const oldBanner = ["<!--", "  GENERATED FROM AGENTS.md — DO NOT EDIT THIS FILE.", "  CLAUDE.md is a generated mirror so Claude Code and Codex read one rulebook.", "  Edit AGENTS.md, then run: npm run claude:generate", "-->", "", ""].join("\n");
function host() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "adg-claude-adapter-"));
  fixtures.push(dir);
  fs.writeFileSync(path.join(dir, "AGENTS.md"), "# Shared rules\n");
  return dir;
}
function run(dir, check = false, expected = 0) {
  const result = spawnSync(process.execPath, [generator, ...(check ? ["--check"] : [])], { cwd: dir, encoding: "utf8" });
  assert.equal(result.status, expected, result.stderr || result.stdout);
  return result;
}
function read(dir, file = "CLAUDE.md") { return fs.readFileSync(path.join(dir, file), "utf8"); }
function write(dir, text) { fs.writeFileSync(path.join(dir, "CLAUDE.md"), text); }
function archived(dir, text) {
  const ref = `docs/adg-preserved/CLAUDE-${hash(text)}.md`;
  assert.equal(read(dir, ref), text);
  assert.ok(read(dir).includes(`(${ref})`), "preserved context must be linked from adapter");
  return ref;
}
let passed = 0;
function test(name, fn) { fn(); passed++; console.log(`  ok ${name}`); }
try {
  test("missing and malformed adapters fail; small adapter survives shared rule edits", () => {
    const dir = host();
    run(dir, true, 1);
    write(dir, "@../../outside.md\n");
    run(dir, true, 1);
    fs.unlinkSync(path.join(dir, "CLAUDE.md"));
    run(dir);
    assert.ok(read(dir).length < 150);
    fs.appendFileSync(path.join(dir, "AGENTS.md"), "New policy.\n");
    run(dir, true);
  });
  test("native init adapter checks and upgrades without bogus archives", () => {
    const dir = host();
    const init = spawnSync(process.execPath, [path.resolve("scripts/adg-init.mjs"), "--target", dir, "--profile", "native", "--client", "claude"], { encoding: "utf8" });
    assert.equal(init.status, 0, init.stderr);
    run(dir, true); run(dir); run(dir, true);
    assert.ok(!fs.existsSync(path.join(dir, "docs/adg-preserved")));
    write(dir, "@AGENTS.md\n"); run(dir, true); run(dir);
    assert.ok(!fs.existsSync(path.join(dir, "docs/adg-preserved")));
  });
  test("unmanaged notes are archived verbatim, linked, and idempotent", () => {
    const dir = host(), notes = "# Claude context\n\nKeep the special deployment command.\n";
    write(dir, notes); run(dir); archived(dir, notes);
    const first = read(dir); run(dir); assert.equal(read(dir), first); run(dir, true);
  });
  test("exact old mirrors migrate without redundant context", () => {
    const dir = host(); write(dir, oldBanner + read(dir, "AGENTS.md")); run(dir);
    assert.ok(!fs.existsSync(path.join(dir, "docs/adg-preserved"))); run(dir, true);
  });
  test("customized and stale legacy mirrors retain their full context", () => {
    for (const source of ["# Shared rules\n\nCustom note.\n", "# Prior shared instructions\n"]) {
      const dir = host(), notes = oldBanner + source; write(dir, notes); run(dir); archived(dir, notes);
    }
  });
  test("customized thin adapter preserves notes and prior archive links", () => {
    const dir = host(), notes = "Initial note.\n";
    write(dir, notes); run(dir); const firstRef = archived(dir, notes);
    const changed = read(dir) + "\nNew note.\n"; write(dir, changed); run(dir);
    const secondRef = archived(dir, changed);
    assert.ok(read(dir, secondRef).includes(firstRef));
    assert.ok(read(dir).includes(firstRef), "earlier context remains directly accessible");
    run(dir, true);
    // Even a historical adapter that links only its latest archive must check
    // older preserved context recursively.
    write(dir, read(dir).replace(`- [Original Claude notes](${firstRef})\n`, ""));
    run(dir, true);
    fs.unlinkSync(path.join(dir, firstRef)); run(dir, true, 1);
  });
  test("archive collision does not overwrite context or the original", () => {
    const dir = host(), notes = "Important context.\n";
    write(dir, notes);
    const ref = `docs/adg-preserved/CLAUDE-${hash(notes)}.md`;
    fs.mkdirSync(path.dirname(path.join(dir, ref)), { recursive: true });
    fs.writeFileSync(path.join(dir, ref), "Distinct archival content.\n");
    run(dir, false, 1);
    assert.equal(read(dir), notes); assert.equal(read(dir, ref), "Distinct archival content.\n");
  });
  test("check detects changed and missing preserved context", () => {
    const dir = host(), notes = "Important context.\n";
    write(dir, notes); run(dir); const ref = archived(dir, notes);
    fs.writeFileSync(path.join(dir, ref), "Modified"); run(dir, true, 1);
    fs.unlinkSync(path.join(dir, ref)); run(dir, true, 1);
  });
  test("symlink targets and source rulebooks are rejected", () => {
    for (const name of ["CLAUDE.md", "AGENTS.md"]) {
      const dir = host(), outside = host();
      if (fs.existsSync(path.join(dir, name))) fs.unlinkSync(path.join(dir, name));
      fs.symlinkSync(path.join(outside, "AGENTS.md"), path.join(dir, name));
      run(dir, false, 1); run(dir, true, 1);
      assert.equal(read(outside, "AGENTS.md"), "# Shared rules\n");
    }
  });
  test("archive directory symlink cannot escape the host", () => {
    const dir = host(), outside = host(), notes = "Keep me.\n";
    write(dir, notes); fs.symlinkSync(outside, path.join(dir, "docs"));
    run(dir, false, 1); assert.equal(read(dir), notes);
    assert.deepEqual(fs.readdirSync(outside), ["AGENTS.md"]);
  });
  test("dangling target symlink is not followed", () => {
    const dir = host(); fs.symlinkSync(path.join(dir, "missing"), path.join(dir, "CLAUDE.md"));
    run(dir, false, 1); assert.ok(!fs.existsSync(path.join(dir, "missing")));
  });
  console.log(`\nClaude adapter: ${passed} checks passed`);
} finally {
  for (const dir of fixtures) fs.rmSync(dir, { recursive: true, force: true });
}
